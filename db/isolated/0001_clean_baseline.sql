  accent_color TEXT NOT NULL CHECK (accent_color ~ '^#[0-9A-Fa-f]{6}$'),
  background_color TEXT NOT NULL CHECK (background_color ~ '^#[0-9A-Fa-f]{6}$'),
  text_color TEXT NOT NULL CHECK (text_color ~ '^#[0-9A-Fa-f]{6}$'),
