BEGIN;

CREATE TABLE site_content (
  key TEXT PRIMARY KEY,
  content_ar TEXT,
  content_en TEXT,
  content_fr TEXT,
  section TEXT NOT NULL DEFAULT 'general',
  type TEXT NOT NULL DEFAULT 'text',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX site_content_active_section ON site_content(is_active, section);

CREATE TABLE site_settings (
  setting_key TEXT PRIMARY KEY,
  setting_value TEXT NOT NULL,
  value_type TEXT NOT NULL DEFAULT 'text',
  label TEXT,
  description TEXT,
  category TEXT NOT NULL DEFAULT 'general',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX site_settings_category ON site_settings(category, setting_key);

CREATE TABLE site_areas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  area_type TEXT NOT NULL CHECK (area_type IN ('global', 'country')),
  country_code CHAR(2),
  name_ar TEXT NOT NULL,
  name_en TEXT,
  name_fr TEXT,
  currency_code CHAR(3) NOT NULL,
  currency_symbol TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK ((area_type = 'global' AND country_code IS NULL) OR (area_type = 'country' AND country_code IS NOT NULL))
);
CREATE UNIQUE INDEX site_areas_country_code_unique ON site_areas(country_code) WHERE country_code IS NOT NULL;

CREATE TABLE area_content (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  area_id BIGINT NOT NULL REFERENCES site_areas(id) ON DELETE CASCADE,
  content_key TEXT NOT NULL,
  content_ar TEXT,
  content_en TEXT,
  content_fr TEXT,
  content_type TEXT NOT NULL DEFAULT 'text',
  section TEXT NOT NULL DEFAULT 'general',
  href TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (area_id, content_key)
);
CREATE INDEX area_content_public_order ON area_content(area_id, is_active, section, sort_order);

CREATE TABLE area_packages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  area_id BIGINT NOT NULL REFERENCES site_areas(id) ON DELETE CASCADE,
  program TEXT NOT NULL CHECK (program IN ('quran', 'arabic', 'other')),
  package_key TEXT NOT NULL,
  name_ar TEXT NOT NULL,
  name_en TEXT,
  name_fr TEXT,
  description_ar TEXT,
  description_en TEXT,
  description_fr TEXT,
  price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
  currency_code CHAR(3) NOT NULL,
  billing_period TEXT NOT NULL DEFAULT 'month',
  sessions_per_month INTEGER NOT NULL CHECK (sessions_per_month > 0),
  duration_minutes SMALLINT NOT NULL DEFAULT 30 CHECK (duration_minutes BETWEEN 1 AND 240),
  features_ar JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(features_ar) = 'array'),
  features_en JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(features_en) = 'array'),
  features_fr JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(features_fr) = 'array'),
  is_popular BOOLEAN NOT NULL DEFAULT FALSE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (area_id, package_key)
);
CREATE INDEX area_packages_public_order ON area_packages(area_id, program, is_active, sort_order);

-- Enforce that package prices cannot be stored under a different country's currency.
CREATE FUNCTION enforce_area_package_currency() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE expected_currency TEXT;
BEGIN
  SELECT currency_code INTO expected_currency FROM site_areas WHERE id = NEW.area_id;
  IF expected_currency IS NULL OR upper(NEW.currency_code) <> upper(expected_currency) THEN
    RAISE EXCEPTION 'Package currency must match its site area currency';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER area_package_currency_guard
  BEFORE INSERT OR UPDATE OF area_id, currency_code ON area_packages
  FOR EACH ROW EXECUTE FUNCTION enforce_area_package_currency();

