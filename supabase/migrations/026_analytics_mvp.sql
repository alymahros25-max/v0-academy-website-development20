DROP POLICY IF EXISTS analytics_sources_service_only ON public.analytics_sources;
CREATE POLICY analytics_sources_service_only ON public.analytics_sources
  FOR ALL TO service_role USING (TRUE) WITH CHECK (TRUE);

DROP POLICY IF EXISTS analytics_snapshots_service_only ON public.analytics_sync_snapshots;
CREATE POLICY analytics_snapshots_service_only ON public.analytics_sync_snapshots
  FOR ALL TO service_role USING (TRUE) WITH CHECK (TRUE);

DROP POLICY IF EXISTS internal_events_service_only ON public.internal_analytics_events;
CREATE POLICY internal_events_service_only ON public.internal_analytics_events
  FOR ALL TO service_role USING (TRUE) WITH CHECK (TRUE);

DROP POLICY IF EXISTS event_deliveries_service_only ON public.analytics_event_deliveries;
CREATE POLICY event_deliveries_service_only ON public.analytics_event_deliveries
  FOR ALL TO service_role USING (TRUE) WITH CHECK (TRUE);

COMMENT ON TABLE public.analytics_sync_snapshots IS 'Aggregate snapshots from GA4 and Search Console; never stores raw visitor identifiers.';
