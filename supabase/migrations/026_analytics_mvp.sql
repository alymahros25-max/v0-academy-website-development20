-- 026: Multi-source analytics MVP storage.
-- Stores aggregate report snapshots and confirmed conversion events only.

CREATE TABLE IF NOT EXISTS public.analytics_sources (
  source_key TEXT PRIMARY KEY,
  display_name TEXT NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  consent_required BOOLEAN NOT NULL DEFAULT FALSE,
  last_attempt_at TIMESTAMPTZ,
  last_success_at TIMESTAMPTZ,
  last_status TEXT NOT NULL DEFAULT 'not_configured' CHECK (last_status IN ('healthy','delayed','failed','disabled','consent_required','not_configured')),
  last_error_code TEXT,
  last_error_message TEXT,
  failure_count INTEGER NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.analytics_sync_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_key TEXT NOT NULL REFERENCES public.analytics_sources(source_key) ON DELETE CASCADE,
  report_type TEXT NOT NULL,
  period_start DATE NOT NULL,
  period_end DATE NOT NULL,
  fetched_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  source_updated_at TIMESTAMPTZ,
  metrics JSONB NOT NULL DEFAULT '{}'::jsonb,
  dimensions JSONB NOT NULL DEFAULT '{}'::jsonb,
  schema_version INTEGER NOT NULL DEFAULT 1,
  response_hash TEXT,
  UNIQUE (source_key, report_type, period_start, period_end, schema_version)
);

CREATE INDEX IF NOT EXISTS analytics_snapshots_lookup_idx
  ON public.analytics_sync_snapshots (source_key, report_type, period_start, period_end, fetched_at DESC);

CREATE TABLE IF NOT EXISTS public.internal_analytics_events (
  event_id TEXT PRIMARY KEY,
  event_name TEXT NOT NULL CHECK (event_name IN ('contact_form_submit','whatsapp_click','telegram_click','email_click','trial_booking_click')),
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  page_path TEXT,
  program TEXT,
  country_group TEXT,
  source_group TEXT,
  device_type TEXT,
  consent_state TEXT,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS internal_analytics_events_lookup_idx
  ON public.internal_analytics_events (event_name, occurred_at DESC);

CREATE TABLE IF NOT EXISTS public.analytics_event_deliveries (
  event_id TEXT NOT NULL REFERENCES public.internal_analytics_events(event_id) ON DELETE CASCADE,
  source_key TEXT NOT NULL REFERENCES public.analytics_sources(source_key) ON DELETE CASCADE,
  delivery_status TEXT NOT NULL DEFAULT 'pending' CHECK (delivery_status IN ('pending','sent','failed','not_applicable')),
  attempt_count INTEGER NOT NULL DEFAULT 0,
  last_attempt_at TIMESTAMPTZ,
  last_error_message TEXT,
  PRIMARY KEY (event_id, source_key)
);

